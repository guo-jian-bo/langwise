class KnowledgeInfo<T> with JsonSerializableMixin {
  final int? unitId;
  final String? unitName;
  final int? unitIndex;
  final String? description;
  final int? lessonCount;
  final List<T>? knowledgeList;

  KnowledgeInfo({this.unitId, this.unitName, this.unitIndex, this.description, this.lessonCount, this.knowledgeList});

  factory KnowledgeInfo.fromJson(Map<String, dynamic> json, {Function? fromJson}) {
    List<T>? knowledgeList = [];
    if (json['knowledgeList'] != null) {
      if (fromJson != null) {
        knowledgeList = json['knowledgeList'].map((e) => fromJson(e)).cast<T>().toList();
      } else {
        knowledgeList = json['knowledgeList'] as List<T>?;
      }
    }
    return KnowledgeInfo(
        unitId: json["unitId"],
        unitName: json["unitName"],
        unitIndex: json["unitIndex"],
        description: json["description"],
        lessonCount: json["lessonCount"],
        knowledgeList: knowledgeList);
  }

  /// 创建当前对象的副本，并可选择性地替换某些字段
  KnowledgeInfo<T> copyWith({
    int? unitId,
    String? unitName,
    int? unitIndex,
    String? description,
    int? lessonCount,
    List<T>? knowledgeList,
  }) {
    return KnowledgeInfo<T>(
      unitId: unitId ?? this.unitId,
      unitName: unitName ?? this.unitName,
      unitIndex: unitIndex ?? this.unitIndex,
      description: description ?? this.description,
      lessonCount: lessonCount ?? this.lessonCount,
      knowledgeList: knowledgeList ?? this.knowledgeList,
    );
  }

  @override
  Map<String, dynamic> toJson() => {
        "unitId": unitId,
        "unitName": unitName,
        "unitIndex": unitIndex,
        "description": description,
        "lessonCount": lessonCount,
        "knowledgeList": knowledgeList,
      };

  /// 相等性判断优化
  @override
  bool operator ==(Object other) => identical(this, other) || (other is KnowledgeInfo && unitId == other.unitId);

  @override
  int get hashCode => unitId.hashCode;

  @override
  String toString() {
    return 'KnowledgeInfo('
        'unitId: $unitId, hashCode:$hashCode,'
        'unitName: $unitName, '
        'unitIndex: $unitIndex, description: $description)';
  }
}
