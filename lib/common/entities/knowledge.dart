/// 语义信息实体类
/// 包含词汇的完整语义信息，包括释义、描述、访问权限等
class SemanticInfo {
  /// 语义信息唯一标识
  final int? uid;

  /// 不同语言的释义列表
  final List<LanguageText>? gloss;

  /// 不同语言的描述列表
  final List<LanguageText>? descriptions;

  /// 访问权限 (如: "NORMAL")
  final String? access;

  /// 更新时间
  final String? updated;

  /// 创建时间
  final String? created;

  const SemanticInfo({
    this.uid,
    this.gloss,
    this.descriptions,
    this.access,
    this.updated,
    this.created,
  });

  /// 从JSON创建实例
  factory SemanticInfo.fromJson(Map<String, dynamic> json) {
    List<LanguageText>? glossList;
    if (json['gloss'] != null) {
      glossList = (json['gloss'] as List).map((e) => LanguageText.fromJson(e)).toList();
    }

    List<LanguageText>? descriptionsList;
    if (json['descriptions'] != null) {
      descriptionsList = (json['descriptions'] as List).map((e) => LanguageText.fromJson(e)).toList();
    }

    return SemanticInfo(
      uid: json["uid"],
      gloss: glossList,
      descriptions: descriptionsList,
      access: json["access"],
      updated: json["updated"],
      created: json["created"],
    );
  }

  /// 转换为JSON
  Map<String, dynamic> toJson() => {
        "uid": uid,
        "gloss": gloss?.map((e) => e.toJson()).toList(),
        "descriptions": descriptions?.map((e) => e.toJson()).toList(),
        "access": access,
        "updated": updated,
        "created": created,
      };

  @override
  String toString() {
    return 'SemanticInfo(uid: $uid, access: $access, gloss: $gloss, descriptions: $descriptions)';
  }
}

