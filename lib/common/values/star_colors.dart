/// 根据星级获取颜色
Color getStarColor(int stars) {
  switch (stars) {
    case 1:
      return color_FB2C36;
    case 2:
      return color_FF6900;
    case 3:
      return color_F0B100;
    case 4:
      return color_2B7FFF;
    case 5:
      return color_00C950;
    default:
      return color_D1D5DC;
  }
}

